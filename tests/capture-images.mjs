import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source = await readFile(new URL('../extension/capture-images.js', import.meta.url), 'utf8');
const {capturePageImages} = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const prefix = 'https://sandstorm-image.invalid/abcdef/';
const images = Array.from({length: 12}, (_, i) => ({placeholder: prefix + i + '.image', url: 'https://images.invalid/' + i}));
const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="10" height="10"><rect width="10" height="10"/></svg>';
const content = images.map(i => '<img src="' + i.placeholder + '">').join('');
let calls = 0;
globalThis.fetch = async (url, options) => {
  calls++;
  assert.equal(options.credentials, 'omit');
  assert.equal(options.redirect, 'error');
  assert.equal(options.referrerPolicy, 'no-referrer');
  assert.equal(options.headers, undefined, 'API token must not be sent');
  const i = Number(url.split('/').pop());
  if (i === 2) throw Error('No host access');
  if (i === 3) return new Response(svg, {headers: {'content-type': 'image/svg+xml'}});
  if (i === 4) return new Response('large', {headers: {'content-type': 'image/png', 'content-length': 4 * 1024 * 1024}});
  return new Response(new Uint8Array([i]), {headers: {'content-type': i === 5 ? 'image/avif' : 'image/png'}});
};
const result = await capturePageImages({content, images});
assert.equal(calls, 12);
assert.ok(result.includes('data:image/svg+xml;base64,' + Buffer.from(svg).toString('base64')));
assert.equal((result.match(/src="data:,"/g) || []).length, 2);
assert.ok(!result.includes('https://images.invalid/'), 'Failed image URL retained');
for (const i of [0,1,5,6,7,8,9,10,11]) assert.ok(result.includes('src="data:image/' + (i === 5 ? 'avif' : 'png') + ';base64,' + Buffer.from([i]).toString('base64') + '"'));
assert.ok(!result.includes('sandstorm-image.invalid'), 'Overlapping numbered placeholders corrupted');
assert.equal(await capturePageImages({content:'plain'}), 'plain');
globalThis.fetch = async () => new Response(new Uint8Array(3 * 1024 * 1024 + 1), {headers: {'content-type':'image/png'}});
assert.equal(await capturePageImages({content:'<img src="' + images[0].placeholder + '">', images:images.slice(0,1)}), '<img src="data:,">');
console.log('PASS: upload collection, token/cookie isolation, inert failure fallback, unsupported/oversized images, placeholder isolation.');
